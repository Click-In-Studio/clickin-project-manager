// 教会模型别瞎发明语法：文档间链接只认一种形态 [#](/__cm__wiki:<uuid>)，
// [[标题]] 只是人类手写时的兜底渲染，不会被记入 wiki_link 边表。
//
// 2026-08-16 用户实测抓到两条真故障，促成本版重写：
// 1. 模型写出 "[#wiki:54d43b4a-...]（世界观报告 5.6 节 piece 草案）"——
//    裸 token 后面又跟一段人类可读说明，语义上下相反。
// 2. 旧版鼓励模型给 markdown 链接形式填"自定义可见文字"（如
//    [世界观报告](/__cm__wiki:<uuid>)），但渲染层其实从不信任这段文字——
//    只在目标文档标题拿不到时才兜底显示它。目标文档一旦改名，这段冻结在
//    正文里的旧标题就会长期挂着不同步，肉眼看起来像是"链接坏了"。
// 现版本把这两个坑一起堵掉：只保留 [#](/__cm__wiki:<uuid>) 一种形态，方括号
// 里固定写 #，渲染时永远用实时标题覆盖，模型完全不用关心、也不该费心填什么
// "有意义的文字"——写了也会被忽略。旧版裸 token [#wiki:<uuid>] 已废弃：它在
// 实际 UI 里从未被渲染成真正的链接，只是原样显示成一段无用的方括号文字。
// 链接之外的三个私有方言（callout/分栏/图片）+ @提及形态。AI 能读懂标准
// markdown 但不认识私有方言——不教就不会用，编辑时还可能当噪音改写掉。
// 与 lib/tiptap-callout.ts / lib/tiptap-columns.ts / lib/tiptap-wiki-image.ts
// 的 canonical 形态同批维护：方言变，这里必须同批变（方言两侧同落纪律的
// 第三落点：编辑器 roundtrip、渲染器、AI 说明书）。
//
// 送达通道（#333 T1）：本说明书不再内联进工具描述（曾占全量工具面 19%），
// 改为三通道按需送达——①温层：用户在文档库/灵感文档页面时随 /inject-context
// 的 knowledge 段注入；②冷层：工具召回命中正文读写工具时随召回闭包携带；
// ③显式：production.wiki_dialect_ref 工具按需拉取（语境中已有时返回指引而非
// 全文，幂等标志由插件覆写）。存储位置不变（repo 内 TS 常量，与方言实现同批
// 提交）——绝不做成 wiki 库文档：进 DB 就脱离版本控制，三落点同批纪律失效。
