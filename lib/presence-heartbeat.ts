/**
 * presence-heartbeat.ts — 在场表的过期 / 心跳契约（#578）。纯常量，客户端与服务端共用。
 *
 * 三条协作流（script / cue / wiki）的在场表都按 `updatedAt` 过期，过期是为了兜住
 * 「连接断了服务端没察觉」的半开 TCP（合上笔记本盖、网络分区：nginx 与 node 要到
 * 内核重传超时才知道，可达十几分钟）。但光标 POST 是「变化时上报」，一个人安静
 * 读文档超过过期窗口就会被清出在场表——他本人连接全程健康，头像却在别人那里
 * 消失，开始打字后（wiki 的光标搭 PATCH 走、条目缺席不写）也回不来。
 *
 * 所以客户端在页面可见期间按固定间隔重发上一次的在场状态（hooks/usePresenceHeartbeat），
 * 服务端收到同值心跳只续 `updatedAt` 不广播。间隔必须留出至少一拍的丢失余量：
 * 心跳 < 过期 / 2。
 *
 * 不选「连接活着即在场」的原因：script 域一个浏览器的多个标签页共用一条 SSE
 * （leader 选举，cid=`stream:<key>`），在场条目却是每标签页一条——在场单位 ≠ 连接单位，
 * 连接拆除时无从知道该摘掉哪些条目。三域同一设计，宜一次收。
 */

/** 服务端：在场条目多久没续就视为不在场。 */
export const PRESENCE_STALE_MS = 90_000;

/** 客户端：页面可见期间的心跳间隔。 */
export const PRESENCE_HEARTBEAT_MS = 30_000;
